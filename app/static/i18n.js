function detectLang() {
  try {
    const saved = localStorage.getItem("lang");
    if (saved && saved in LANGS) return saved;
  } catch { /* yksityinen tila tms. */ }
  for (const l of navigator.languages || [navigator.language || ""]) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (code in LANGS) return code;
  }
  return "en";
}

let LANG = detectLang();
document.documentElement.lang = LANG;

function t(key, params) {
  let s = (LANG !== "fi" && DICT[LANG] && DICT[LANG][key]) || key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

function setLang(code) {
  if (!(code in LANGS)) return;
  LANG = code;
  document.documentElement.lang = code;
  try { localStorage.setItem("lang", code); } catch { /* ei tallennusta */ }
}
