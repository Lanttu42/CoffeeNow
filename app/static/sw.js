// COFFEE!! service worker: vastaanottaa push-ilmoitukset ja avaa oikean keittimen klikatessa.

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));

self.addEventListener("push", (event) => {
  let data = { title: "COFFEE!!", body: "Kahvitilanne muuttui", url: "/" };
  try {
    data = { ...data, ...event.data.json() };
  } catch (e) { /* ei payloadia -> oletusteksti */ }

  event.waitUntil(
    self.registration.showNotification(data.title, {
      body: data.body,
      icon: "/static/icon-192.png",
      badge: "/static/icon-192.png",
      tag: data.url,          // saman keittimen ilmoitukset korvaavat toisensa
      renotify: true,
      data: { url: data.url },
    })
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || "/";
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((wins) => {
      for (const w of wins) {
        if ("focus" in w) { w.navigate(url); return w.focus(); }
      }
      return self.clients.openWindow(url);
    })
  );
});
